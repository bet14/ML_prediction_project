"""
scripts/generate_dataset_comparison_report.py

Generates a standalone HTML report comparing Dataset 1 (Basic Daily), Dataset 2
(90-Day Lookback), and Dataset 3 (Technical Indicators) across all 12 registry models.

Reads reports/tables/model_comparison.csv and reports/figures/dataset_comparison_*.png
(generated by scripts/plot_dataset_comparison.py -- run that first).

Usage:
    python scripts/plot_dataset_comparison.py            # generate charts first
    python scripts/generate_dataset_comparison_report.py
    python scripts/generate_dataset_comparison_report.py --open
"""

import argparse
import base64
import datetime
import html as _html
import sys
from pathlib import Path

import pandas as pd

ROOT     = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "reports" / "tables" / "model_comparison.csv"
FIG_DIR  = ROOT / "reports" / "figures"
OUT_FILE = ROOT / "reports" / "dataset_comparison.html"

CV_FOLDS = ["1", "2", "3", "4", "5"]

DATASET_ORDER  = ["dataset_basic_daily", "dataset_90day_lookback", "dataset_technical"]
DATASET_LABELS = {
    "dataset_basic_daily":    "Dataset 1 — Basic Daily",
    "dataset_90day_lookback": "Dataset 2 — 90-Day Lookback",
    "dataset_technical":      "Dataset 3 — Technical Indicators",
}
MODEL_ORDER = ["LR", "Bagging_LR", "HGB", "CatBoost", "LGBM", "XGB",
               "Bagging_DT", "RF", "ET", "MLP", "KNN", "DT"]

FIGURES = [
    ("dataset_comparison_accuracy.png",    "CV Mean Accuracy by Dataset"),
    ("dataset_comparison_auc.png",         "CV Mean AUC-ROC by Dataset"),
    ("dataset_comparison_sharpe.png",      "CV Mean Sharpe Proxy by Dataset"),
    ("dataset_comparison_overfit_gap.png", "Overfitting Gap (CV - Final) by Dataset"),
]


def load_df() -> pd.DataFrame:
    if not CSV_PATH.exists():
        sys.exit(f"File not found: {CSV_PATH}\nRun train.py first.")
    return pd.read_csv(CSV_PATH)


def summary_table(df: pd.DataFrame) -> pd.DataFrame:
    """One row per (dataset, model): CV mean + Final + gap, for all 5 metrics."""
    metrics = ["accuracy", "f1_macro", "auc_roc", "sharpe_proxy", "max_drawdown"]
    cv = (
        df[df["fold"].isin(CV_FOLDS)]
        .groupby(["dataset", "model"])[metrics]
        .mean()
        .rename(columns={m: f"{m}_cv" for m in metrics})
    )
    final = (
        df[df["fold"] == "final"]
        .groupby(["dataset", "model"])[metrics]
        .first()
        .rename(columns={m: f"{m}_final" for m in metrics})
    )
    out = cv.join(final, how="outer").reset_index()
    out["overfit_gap_acc"] = out["accuracy_cv"] - out["accuracy_final"]

    out["dataset"] = pd.Categorical(out["dataset"], categories=DATASET_ORDER, ordered=True)
    out["model"] = pd.Categorical(out["model"], categories=MODEL_ORDER, ordered=True)
    out = out.sort_values(["dataset", "model"]).reset_index(drop=True)
    return out


def fmt_pct(x) -> str:
    return "—" if pd.isna(x) else f"{x:.1%}"


def fmt_num(x, nd=3) -> str:
    return "—" if pd.isna(x) else f"{x:.{nd}f}"


def build_table_html(summary: pd.DataFrame, dataset_key: str) -> str:
    sub = summary[summary["dataset"] == dataset_key]
    rows = []
    for _, r in sub.iterrows():
        gap = r["overfit_gap_acc"]
        gap_cls = "gap-warn" if pd.notna(gap) and gap > 0.05 else ""
        rows.append(
            "<tr>"
            f"<td class='model-cell'>{_html.escape(str(r['model']))}</td>"
            f"<td>{fmt_pct(r['accuracy_cv'])}</td>"
            f"<td>{fmt_pct(r['accuracy_final'])}</td>"
            f"<td>{fmt_num(r['auc_roc_cv'])}</td>"
            f"<td>{fmt_num(r['auc_roc_final'])}</td>"
            f"<td>{fmt_num(r['f1_macro_cv'])}</td>"
            f"<td>{fmt_num(r['sharpe_proxy_cv'], 2)}</td>"
            f"<td>{fmt_num(r['max_drawdown_cv'], 3)}</td>"
            f"<td class='{gap_cls}'>{fmt_pct(gap)}</td>"
            "</tr>"
        )
    return (
        "<table class='metrics-table'>"
        "<thead><tr>"
        "<th>Model</th><th>Acc CV</th><th>Acc Final</th>"
        "<th>AUC CV</th><th>AUC Final</th><th>F1 CV</th>"
        "<th>Sharpe CV</th><th>MaxDD CV</th><th>Overfit Gap</th>"
        "</tr></thead><tbody>"
        + "\n".join(rows) +
        "</tbody></table>"
    )


def img_b64(path: Path) -> str:
    if not path.exists():
        return ""
    return base64.b64encode(path.read_bytes()).decode("ascii")


