def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--open", action="store_true", help="Open the HTML report after generating.")
    args = ap.parse_args()

    print("Loading model_comparison.csv ...")
    df = load_df()
    print(f"  {len(df)} rows | datasets: {sorted(df['dataset'].unique())}")

    print("Building summary table ...")
    summary = summary_table(df)

    print("Embedding chart images ...")
    figs_b64 = {}
    for fname, title in FIGURES:
        path = FIG_DIR / fname
        b64 = img_b64(path)
        if not b64:
            print(f"  WARNING: {fname} not found -- run scripts/plot_dataset_comparison.py first.")
        figs_b64[fname] = b64

    print("Building HTML ...")
    htm = build_html(summary, figs_b64)

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(htm, encoding="utf-8")
    size_kb = OUT_FILE.stat().st_size / 1024
    print(f"Saved: {OUT_FILE.relative_to(ROOT)}  ({size_kb:.0f} KB)")

    if args.open:
        import webbrowser
        webbrowser.open(OUT_FILE.as_uri())
        print("Opened in browser.")
    else:
        print(f"Open manually: {OUT_FILE}")


if __name__ == "__main__":
    main()
